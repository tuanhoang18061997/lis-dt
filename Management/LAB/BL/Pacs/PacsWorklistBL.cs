        private async Task<string>
            GenerateNextAccessionNumberAsync(string prefix)
        {
            var expectedLength = prefix.Length + AccessionSuffixLength;

            var resultValues =
                await _context.ResultCDHAs
                    .AsNoTracking()
                    .Where(x =>
                        x.AccessionNumber != null &&
                        x.AccessionNumber.StartsWith(prefix) &&
                        x.AccessionNumber.Length == expectedLength)
                    .Select(x => x.AccessionNumber)
                    .ToListAsync();

            var worklistValues =
                await _context.PacsWorklistItems
                    .AsNoTracking()
                    .Where(x =>
                        x.AccessionNumber != null &&
                        x.AccessionNumber.StartsWith(prefix) &&
                        x.AccessionNumber.Length == expectedLength)
                    .Select(x => x.AccessionNumber)
                    .ToListAsync();

            var currentMax = 0;

            foreach (var accession in resultValues.Concat(worklistValues))
            {
                if (string.IsNullOrWhiteSpace(accession))
                    continue;

                var value = accession.Trim();

                if (value.Length != expectedLength)
                    continue;

                var suffix = value.Substring(prefix.Length);

                if (suffix.Length != AccessionSuffixLength)
                    continue;

                if (!suffix.All(char.IsDigit))
                    continue;

                if (IsOldDateBasedAccessionSuffix(suffix))
                    continue;

                if (int.TryParse(
                        suffix,
                        NumberStyles.None,
                        CultureInfo.InvariantCulture,
                        out var number) &&
                    number > currentMax)
                {
                    currentMax = number;
                }
            }

            var nextNumber = currentMax + 1;

            if (nextNumber <= 0 ||
                nextNumber > AccessionSuffixMax)
            {
                throw new InvalidOperationException(
                    $"Không thể tạo AccessionNumber prefix={prefix}. " +
                    $"Đã vượt quá {AccessionSuffixMax:N0} số.");
            }

            return $"{prefix}{nextNumber:D8}";
        }

        private async Task<string?>
            FindAccessionConflictAsync(
                long resultCDHAId,
                string accessionNumber)
        {
            if (string.IsNullOrWhiteSpace(accessionNumber))
                return null;

            var resultConflict =
                await _context.ResultCDHAs
                    .AsNoTracking()
                    .Where(x =>
                        x.Id != resultCDHAId &&
                        x.AccessionNumber == accessionNumber)
                    .Select(x => (long?)x.Id)
                    .FirstOrDefaultAsync();

            if (resultConflict.HasValue)
            {
                return
                    $"AccessionNumber={accessionNumber} đã thuộc " +
                    $"ResultCDHAId={resultConflict.Value}.";
            }

            var worklistConflict =
                await _context.PacsWorklistItems
                    .AsNoTracking()
                    .Where(x =>
                        x.ResultCDHAId != resultCDHAId &&
                        x.AccessionNumber == accessionNumber)
                    .Select(x => (long?)x.ResultCDHAId)
                    .FirstOrDefaultAsync();

            if (worklistConflict.HasValue)
            {
                return
                    $"AccessionNumber={accessionNumber} đã thuộc " +
                    $"PacsWorklistItem của ResultCDHAId=" +
                    $"{worklistConflict.Value}.";
            }

            return null;
        }

