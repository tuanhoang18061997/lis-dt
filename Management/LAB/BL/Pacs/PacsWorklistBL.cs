        public async Task<PacsWorklistCreateResult>
    CreateWorklistForResultCDHAAsync(
        long resultCDHAId,
        string categoryCode,
        DateTime? scheduledAt = null,
        long? userId = null)
        {
            if (resultCDHAId <= 0)
            {
                return new PacsWorklistCreateResult
                {
                    Success = false,
                    ResultCDHAId = resultCDHAId,
                    ErrorCode = "INVALID_RESULT_ID",
                    Message = "ResultCDHAId không hợp lệ."
                };
            }

            // ============================================================
            // HOTFIX:
            // AccessionNumber là identity của ResultCDHA.
            // Phải được đảm bảo trước khi phụ thuộc filesystem MWL.
            //
            // Nhờ vậy:
            // - Ubuntu/PACS chưa sẵn sàng vẫn tạo AccessionNumber.
            // - Worklist publish có thể fail theo best-effort.
            // - Không làm mất identity đã tạo.
            // ============================================================
            var accessionResult =
                await EnsureAccessionNumberAsync(
                    resultCDHAId,
                    categoryCode);

            if (!accessionResult.Success)
            {
                return new PacsWorklistCreateResult
                {
                    Success = false,
                    ResultCDHAId = resultCDHAId,
                    AccessionNumber =
                        accessionResult.AccessionNumber ?? string.Empty,
                    ErrorCode =
                        accessionResult.ErrorCode,
                    Message =
                        accessionResult.Message,
                    ErrorMessage =
                        accessionResult.ErrorMessage
                };
            }

            FileStream? createLock = null;

            try
            {
                createLock =
                    await AcquireWorklistCreateLockAsync(
                        resultCDHAId,
                        timeoutSeconds: 60);

                // PACS-PROD-05B-03A: scope SMB access to this publish.
                // Staging and quarantine remain on the local Windows volume.
                await using var remoteShare =
                    await PacsSmbConnectionScope.OpenAsync(_configuration);

                return await CreateWorklistForResultCDHACoreAsync(
                    resultCDHAId,
                    categoryCode,
                    scheduledAt,
                    userId);
            }
            catch (TimeoutException ex)
            {
                return new PacsWorklistCreateResult
                {
                    Success = false,
                    ResultCDHAId = resultCDHAId,
                    AccessionNumber =
                        accessionResult.AccessionNumber ?? string.Empty,
                    ErrorCode = "CREATE_LOCK_TIMEOUT",
                    Message =
                        "Worklist đang được request khác xử lý. " +
                        "Không lấy được lock trong thời gian cho phép.",
                    ErrorMessage = ex.Message
                };
            }
            catch (Exception ex)
            {
                return new PacsWorklistCreateResult
                {
                    Success = false,
                    ResultCDHAId = resultCDHAId,
                    AccessionNumber =
                        accessionResult.AccessionNumber ?? string.Empty,
                    ErrorCode = "CREATE_WORKLIST_ERROR",
                    Message =
                        "Đã đảm bảo AccessionNumber nhưng chưa tạo/publish được PACS Worklist.",
                    ErrorMessage = ex.ToString()
                };
            }
            finally
            {
                if (createLock != null)
                {
                    await createLock.DisposeAsync();
                }
            }
        }

        private async Task<PacsWorklistCreateResult>
            CreateWorklistForResultCDHACoreAsync(
                long resultCDHAId,
                string categoryCode,
                DateTime? scheduledAt,
                long? userId)
        {
            var response = new PacsWorklistCreateResult
            {
                Success = false,
                ResultCDHAId = resultCDHAId
            };

            categoryCode = NormalizeCategoryCode(categoryCode);

            if (string.IsNullOrWhiteSpace(categoryCode))
            {
                response.ErrorCode = "INVALID_CATEGORY";
                response.Message = "CategoryCode không được rỗng.";
                return response;
            }

            var resultCDHA =
                await _context.ResultCDHAs
                    .Include(x => x.Patient)
                    .Include(x => x.Service)
                        .ThenInclude(x => x.Category)
                    .Include(x => x.Doctor)
                    .FirstOrDefaultAsync(x => x.Id == resultCDHAId);

            if (resultCDHA == null)
            {
                response.ErrorCode = "RESULT_NOT_FOUND";
                response.Message =
                    $"Không tìm thấy ResultCDHAId={resultCDHAId}.";
                return response;
            }

            if (resultCDHA.Patient == null)
            {
                response.ErrorCode = "PATIENT_NOT_FOUND";
                response.Message =
                    $"ResultCDHAId={resultCDHAId} không có Patient.";
                return response;
            }

            if (resultCDHA.Service == null)
            {
                response.ErrorCode = "SERVICE_NOT_FOUND";
                response.Message =
                    $"ResultCDHAId={resultCDHAId} không có Service.";
                return response;
            }

            var actualCategoryCode =
                NormalizeCategoryCode(
                    resultCDHA.Service.Category?.Code);

            if (!string.IsNullOrWhiteSpace(actualCategoryCode) &&
                actualCategoryCode != categoryCode)
            {
                response.ErrorCode = "CATEGORY_MISMATCH";
                response.Message =
                    $"CategoryCode request={categoryCode} không khớp " +
                    $"Service.Category.Code={actualCategoryCode}.";
                return response;
            }

            var accessionResult =
                await EnsureAccessionNumberAsync(
                    resultCDHAId,
                    categoryCode);

            if (!accessionResult.Success)
            {
                response.ErrorCode = accessionResult.ErrorCode;
                response.Message = accessionResult.Message;
                response.ErrorMessage = accessionResult.ErrorMessage;
                return response;
            }

            var accessionNumber =
                accessionResult.AccessionNumber;

            response.AccessionNumber = accessionNumber;

            var modality =
                ResolveDicomModality(categoryCode);

            var stationAe =
                ResolveScheduledStationAETitle(
                    categoryCode,
                    modality);

            var stationName =
                ResolveScheduledStationName(
                    categoryCode,
                    modality);

            var location =
                ResolveScheduledProcedureStepLocation(
                    categoryCode,
                    modality);

            var procedureStatus =
                ResolveScheduledProcedureStepStatus();

            var scheduledDateTime =
                scheduledAt
                ?? ResolveScheduledDateTime(
                    resultCDHA,
                    categoryCode)
                ?? DateTime.Now;

            var patient = resultCDHA.Patient;
            var service = resultCDHA.Service;

            var draft =
                new PacsMwlDraft
                {
                    ResultCDHAId = resultCDHA.Id,
                    AccessionNumber = accessionNumber,
                    StudyInstanceUID =
                        GenerateStableStudyInstanceUid(accessionNumber),

                    PatientCode =
                        patient.PatientId?.Trim() ?? "",
                    PatientName =
                        patient.PatientName?.Trim() ?? "",
                    PatientBirthDate = null,
                    PatientSex =
                        NormalizeSex(patient.Sex),

                    ReferringPhysicianName =
                        resultCDHA.Doctor?.Name ?? "",
                    InstitutionName =
                        _configuration["Pacs:InstitutionName"] ?? "",

                    ServiceCode = service.Code ?? "",
                    ServiceName = service.Name ?? "",
                    CategoryCode = categoryCode,
                    Modality = modality,

                    RequestedProcedureId = accessionNumber,
                    RequestedProcedureDescription =
                        service.Name ?? "",

                    ScheduledStationAETitle = stationAe,
                    ScheduledStationName = stationName,
                    ScheduledProcedureStepLocation = location,
                    ScheduledProcedureStepStatus = procedureStatus,

                    ScheduledProcedureStepId = accessionNumber,
                    ScheduledProcedureStepStartDate =
                        scheduledDateTime.Date,
                    ScheduledProcedureStepStartTime =
                        scheduledDateTime.TimeOfDay,
                    ScheduledProcedureStepDescription =
                        service.Name ?? "",
                    ScheduledPerformingPhysicianName = "",

                    StudyDescription = service.Name ?? ""
                };

            response.Modality = draft.Modality;
            response.ScheduledStationAETitle =
                draft.ScheduledStationAETitle;
            response.StudyInstanceUID =
                draft.StudyInstanceUID;

            var existingRows =
                await _context.PacsWorklistItems
                    .Where(x => x.ResultCDHAId == resultCDHAId)
                    .OrderBy(x => x.Id)
                    .ToListAsync();

            if (existingRows.Count > 1)
            {
                response.ErrorCode = "DUPLICATE_WORKLIST_ROWS";
                response.Message =
                    $"ResultCDHAId={resultCDHAId} có " +
                    $"{existingRows.Count} PacsWorklistItems. " +
                    "Dừng publish để tránh lấy nhầm Worklist.";
                return response;
            }

            var item =
                existingRows.FirstOrDefault();

            if (item != null &&
                !string.IsNullOrWhiteSpace(item.AccessionNumber) &&
                !string.Equals(
                    item.AccessionNumber.Trim(),
                    accessionNumber,
                    StringComparison.OrdinalIgnoreCase))
            {
                response.ErrorCode =
                    "WORKLIST_ACCESSION_CONFLICT";

                response.Message =
                    $"PacsWorklistItem.Id={item.Id} đang có " +
                    $"AccessionNumber={item.AccessionNumber}, " +
                    $"không khớp ResultCDHA={accessionNumber}.";
                return response;
            }

            // PACS-07A-11F-02A: prevent completed Worklist republish.
            // Guard historical rows where Status was reset to Published after PACS sync.
            if (item != null &&
                (item.Status == 3 ||
                 item.CompletedOn.HasValue ||
                 !string.IsNullOrWhiteSpace(item.OrthancStudyId)))
            {
                response.Success = true;
                response.Skipped = true;
                response.PacsWorklistItemId = item.Id;
                response.DumpFilePath = item.DumpFilePath ?? string.Empty;
                response.WorklistFilePath = item.WorklistFilePath ?? string.Empty;
                response.Message =
                    "WORKLIST_ALREADY_COMPLETED: Study already completed; " +
                    "skip Worklist republish.";
                return response;
            }

            var worklistFolder =
                GetWorklistFolder();

            Directory.CreateDirectory(worklistFolder);

            var safeAccession =
                MakeSafeFileName(accessionNumber);

            var finalWorklistPath =
                Path.Combine(
                    worklistFolder,
                    $"{safeAccession}.wl");

            // DB says published is not enough. Verify the live file.
            if (item != null &&
                item.Status == 1 &&
                item.PublishedOn.HasValue &&
                File.Exists(finalWorklistPath))
            {
                var existingFileValidation =
                    await ValidatePublishedWorklistAsync(
                        finalWorklistPath,
                        draft);

                if (existingFileValidation.Success)
                {
                    response.Success = true;
                    response.Skipped = true;
                    response.PacsWorklistItemId = item.Id;
                    response.DumpFilePath =
                        item.DumpFilePath ?? "";
                    response.WorklistFilePath =
                        finalWorklistPath;
                    response.Message =
                        "Worklist đã publish hợp lệ trước đó, giữ nguyên và bỏ qua tạo lại.";
                    return response;
                }
            }

            var now = DateTime.Now;

            if (item == null)
            {
                item = new PacsWorklistItem
                {
                    ResultCDHAId = resultCDHAId,
                    CreatedOn = now,
                    CreatedBy = userId,
                    Status = 0
                };

                _context.PacsWorklistItems.Add(item);
            }
            else
            {
                item.UpdatedOn = now;
                item.UpdatedBy = userId;
            }

            PopulateWorklistItem(
                item,
                resultCDHA,
                draft);

            item.DumpFileName = null;
            item.DumpFilePath = null;
            item.WorklistFileName = null;
            item.WorklistFilePath = null;
            item.PublishedOn = null;
            item.Status = 0;
            item.ErrorMessage = null;

            await _context.SaveChangesAsync();

            response.PacsWorklistItemId = item.Id;

            var publishResult =
                await CreateValidateAndPublishWorklistAsync(
                    draft);

            item.DumpFileName =
                publishResult.DumpFileName;
            item.DumpFilePath =
                publishResult.DumpFilePath;
            item.WorklistFileName =
                publishResult.WorklistFileName;
            item.WorklistFilePath =
                publishResult.WorklistFilePath;

            response.DumpFilePath =
                publishResult.DumpFilePath;
            response.WorklistFilePath =
                publishResult.WorklistFilePath;
            response.QuarantineDumpPath =
                publishResult.QuarantineDumpPath;
            response.QuarantineWorklistPath =
                publishResult.QuarantineWorklistPath;

            if (!publishResult.Success)
            {
                item.Status = 9;
                item.ErrorMessage =
                    publishResult.Message;
                item.UpdatedOn = DateTime.Now;
                item.UpdatedBy = userId;

                await _context.SaveChangesAsync();

                response.Success = false;
                response.ErrorCode = "PUBLISH_FAILED";
                response.Message =
                    publishResult.Message;
                return response;
            }

            item.Status = 1;
            item.ErrorMessage = null;
            item.PublishedOn = DateTime.Now;
            item.UpdatedOn = DateTime.Now;
            item.UpdatedBy = userId;

            await _context.SaveChangesAsync();

            response.Success = true;
            response.Skipped = false;
            response.Message =
                "Tạo, validate và publish Result-level PACS Worklist thành công.";

            return response;
        }


