        private string GetWorklistCreateLockFolder()
        {
            return Path.Combine(
                GetWorklistStagingFolder(),
                "_locks");
        }

        private async Task<FileStream>
            AcquireWorklistCreateLockAsync(
                long resultCDHAId,
                int timeoutSeconds)
        {
            var lockFolder =
                GetWorklistCreateLockFolder();

            Directory.CreateDirectory(lockFolder);

            var lockFilePath =
                Path.Combine(
                    lockFolder,
                    $"result_{resultCDHAId}.lock");

            var stopwatch =
                Stopwatch.StartNew();

            Exception? lastException = null;

            while (stopwatch.Elapsed <
                   TimeSpan.FromSeconds(timeoutSeconds))
            {
                try
                {
                    return new FileStream(
                        lockFilePath,
                        FileMode.OpenOrCreate,
                        FileAccess.ReadWrite,
                        FileShare.None,
                        bufferSize: 4096,
                        FileOptions.None);
                }
                catch (IOException ex)
                {
                    lastException = ex;
                    await Task.Delay(200);
                }
            }

            throw new TimeoutException(
                $"Không lấy được Worklist create lock " +
                $"cho ResultCDHAId={resultCDHAId} " +
                $"sau {timeoutSeconds} giây.",
                lastException);
        }

        private async Task<PacsWorklistPublishResult>
            CreateValidateAndPublishWorklistAsync(
                PacsMwlDraft draft)
        {
            var result =
                new PacsWorklistPublishResult();

            var stagingFolder =
                GetWorklistStagingFolder();

            var watchedFolder =
                GetWorklistFolder();

            var quarantineFolder =
                GetWorklistQuarantineFolder();

            Directory.CreateDirectory(stagingFolder);
            Directory.CreateDirectory(watchedFolder);
            Directory.CreateDirectory(quarantineFolder);

            var safeAccession =
                MakeSafeFileName(
                    draft.AccessionNumber);

            var dumpFileName =
                $"{safeAccession}.dump";

            var worklistFileName =
                $"{safeAccession}.wl";

            var stagingDumpPath =
                Path.Combine(
                    stagingFolder,
                    dumpFileName);

            var stagingWlPath =
                Path.Combine(
                    stagingFolder,
                    worklistFileName);

            var publishingPath =
                Path.Combine(
                    watchedFolder,
                    $"{safeAccession}.publishing");

            var finalWlPath =
                Path.Combine(
                    watchedFolder,
                    worklistFileName);

            result.DumpFileName = dumpFileName;
            result.DumpFilePath = stagingDumpPath;
            result.WorklistFileName = worklistFileName;
            result.WorklistFilePath = finalWlPath;

            try
            {
                TryDeleteFile(stagingDumpPath);
                TryDeleteFile(stagingWlPath);

                if (File.Exists(publishingPath))
                {
                    result.QuarantineWorklistPath =
                        CopyFileToQuarantine(
                            publishingPath,
                            draft.AccessionNumber);

                    File.Delete(publishingPath);
                }

                var dumpContent =
                    BuildWorklistDump(draft);

                await File.WriteAllTextAsync(
                    stagingDumpPath,
                    dumpContent,
                    new UTF8Encoding(false));

                var convert =
                    await RunProcessAsync(
                        GetDump2DcmPath(),
                        new[]
                        {
                            stagingDumpPath,
                            stagingWlPath
                        },
                        stagingFolder,
                        timeoutMilliseconds: 15000);

                if (!convert.Success ||
                    !File.Exists(stagingWlPath))
                {
                    result.Message =
                        "dump2dcm không tạo được staging Worklist.";

                    result.QuarantineDumpPath =
                        CopyFileToQuarantineIfExists(
                            stagingDumpPath,
                            draft.AccessionNumber);

                    result.QuarantineWorklistPath =
                        CopyFileToQuarantineIfExists(
                            stagingWlPath,
                            draft.AccessionNumber);

                    return result;
                }

                var stagingValidation =
                    await ValidatePublishedWorklistAsync(
                        stagingWlPath,
                        draft);

                if (!stagingValidation.Success)
                {
                    result.Message =
                        "Staging Worklist không hợp lệ. " +
                        stagingValidation.Message;

                    result.QuarantineDumpPath =
                        CopyFileToQuarantineIfExists(
                            stagingDumpPath,
                            draft.AccessionNumber);

                    result.QuarantineWorklistPath =
                        CopyFileToQuarantineIfExists(
                            stagingWlPath,
                            draft.AccessionNumber);

                    return result;
                }

                if (File.Exists(finalWlPath))
                {
                    var finalValidation =
                        await ValidatePublishedWorklistAsync(
                            finalWlPath,
                            draft);

                    if (finalValidation.Success)
                    {
                        result.Success = true;
                        result.ReusedExistingFinal = true;
                        result.Message =
                            "Final Worklist đã tồn tại và hợp lệ, dùng lại.";

                        TryDeleteFile(stagingWlPath);
                        return result;
                    }

                    var invalidPublishedPath =
                        Path.Combine(
                            watchedFolder,
                            $"{safeAccession}.invalid_" +
                            $"{DateTime.Now:yyyyMMdd_HHmmssfff}");

                    File.Move(
                        finalWlPath,
                        invalidPublishedPath);

                    result.QuarantineWorklistPath =
                        CopyFileToQuarantine(
                            invalidPublishedPath,
                            draft.AccessionNumber);

                    TryDeleteFile(invalidPublishedPath);
                }

                File.Copy(
                    stagingWlPath,
                    publishingPath,
                    overwrite: false);

                var publishingValidation =
                    await ValidatePublishedWorklistAsync(
                        publishingPath,
                        draft);

                if (!publishingValidation.Success)
                {
                    result.Message =
                        "File .publishing không hợp lệ. " +
                        publishingValidation.Message;

                    result.QuarantineWorklistPath =
                        CopyFileToQuarantine(
                            publishingPath,
                            draft.AccessionNumber);

                    TryDeleteFile(publishingPath);
                    return result;
                }

                // Atomic visibility switch inside the watched folder.
                File.Move(
                    publishingPath,
                    finalWlPath);

                TryDeleteFile(stagingWlPath);

                result.Success = true;
                result.Message =
                    "Tạo, validate và controlled-publish Worklist thành công.";

                return result;
            }
            catch (Exception ex)
            {
                result.Success = false;
                result.Message =
                    $"Worklist safe pipeline thất bại: {ex.Message}";

                try
                {
                    result.QuarantineDumpPath =
                        CopyFileToQuarantineIfExists(
                            stagingDumpPath,
                            draft.AccessionNumber)
                        ?? result.QuarantineDumpPath;

                    result.QuarantineWorklistPath =
                        CopyFileToQuarantineIfExists(
                            stagingWlPath,
                            draft.AccessionNumber)
                        ?? result.QuarantineWorklistPath;

                    if (File.Exists(publishingPath))
                    {
                        result.QuarantineWorklistPath =
                            CopyFileToQuarantine(
                                publishingPath,
                                draft.AccessionNumber);

                        TryDeleteFile(publishingPath);
                    }
                }
                catch
                {
                    // Preserve original pipeline error.
                }

                return result;
            }
        }

        private async Task<PacsSimpleValidationResult>
            ValidatePublishedWorklistAsync(
                string filePath,
                PacsMwlDraft draft)
        {
            if (!File.Exists(filePath))
            {
                return new PacsSimpleValidationResult
                {
                    Success = false,
                    Message =
                        $"Không tìm thấy Worklist: {filePath}"
                };
            }

            var run =
                await RunProcessAsync(
                    GetDcmDumpPath(),
                    new[]
                    {
                        "+L",
                        filePath
                    },
                    Path.GetDirectoryName(filePath)
                    ?? GetWorklistStagingFolder(),
                    timeoutMilliseconds: 15000);

            if (!run.Success)
            {
                return new PacsSimpleValidationResult
                {
                    Success = false,
                    Message =
                        $"dcmdump thất bại. ExitCode={run.ExitCode}. " +
                        $"{CombineProcessOutput(run.StdOut, run.StdErr)}"
                };
            }

            var output =
                CombineProcessOutput(
                    run.StdOut,
                    run.StdErr);

            var validations =
                BuildMwlValidationChecks(
                    output,
                    draft);

            var failed =
                validations
                    .Where(x => !x.Passed)
                    .Select(x => x.TagName)
                    .ToList();

            if (failed.Count > 0)
            {
                return new PacsSimpleValidationResult
                {
                    Success = false,
                    Message =
                        "Sai/thiếu tag: " +
                        string.Join(", ", failed)
                };
            }

            return new PacsSimpleValidationResult
            {
                Success = true,
                Message = "Worklist hợp lệ."
            };
        }

        private string?
            CopyFileToQuarantineIfExists(
                string sourcePath,
                string accessionNumber)
        {
            if (!File.Exists(sourcePath))
                return null;

            return CopyFileToQuarantine(
                sourcePath,
                accessionNumber);
        }

        private string
            CopyFileToQuarantine(
                string sourcePath,
                string accessionNumber)
        {
            var quarantineFolder =
                GetWorklistQuarantineFolder();

            Directory.CreateDirectory(
                quarantineFolder);

            var safeAccession =
                MakeSafeFileName(
                    accessionNumber);

            var extension =
                Path.GetExtension(sourcePath);

            if (string.IsNullOrWhiteSpace(extension))
                extension = ".bin";

            var fileName =
                $"{safeAccession}_" +
                $"{DateTime.Now:yyyyMMdd_HHmmssfff}_" +
                $"{Guid.NewGuid():N}" +
                extension;

            var targetPath =
                Path.Combine(
                    quarantineFolder,
                    fileName);

            File.Copy(
                sourcePath,
                targetPath,
                overwrite: false);

            return targetPath;
        }

