        }

        private static async Task<PacsProcessResult>
            RunProcessAsync(
                string executablePath,
                IReadOnlyList<string> arguments,
                string workingDirectory,
                int timeoutMilliseconds)
        {
            if (string.IsNullOrWhiteSpace(
                    executablePath))
            {
                return PacsProcessResult.Fail(
                    -1,
                    "",
                    "Executable path rỗng.");
            }

            if (!File.Exists(
                    executablePath))
            {
                return PacsProcessResult.Fail(
                    -1,
                    "",
                    $"Không tìm thấy executable: {executablePath}");
            }

            var psi =
                new ProcessStartInfo
                {
                    FileName =
                        executablePath,

                    WorkingDirectory =
                        workingDirectory,

                    UseShellExecute =
                        false,

                    RedirectStandardOutput =
                        true,

                    RedirectStandardError =
                        true,

                    CreateNoWindow =
                        true
                };

            foreach (var argument in arguments)
            {
                psi.ArgumentList.Add(
                    argument);
            }

            using var process =
                new Process
                {
                    StartInfo = psi
                };

            process.Start();

            var stdoutTask =
                process.StandardOutput
                    .ReadToEndAsync();

            var stderrTask =
                process.StandardError
                    .ReadToEndAsync();

            using var cts =
                new CancellationTokenSource(
                    timeoutMilliseconds);

            try
            {
                await process.WaitForExitAsync(
                    cts.Token);
            }
            catch (OperationCanceledException)
            {
                try
                {
                    process.Kill(
                        entireProcessTree: true);
                }
                catch
                {
                    // Best-effort cleanup.
                }

                return PacsProcessResult.Fail(
                    -1,
                    await stdoutTask,
                    "Process timeout.");
            }

            var stdout =
                await stdoutTask;

            var stderr =
                await stderrTask;

            return new PacsProcessResult
            {
                Success =
                    process.ExitCode == 0,

                ExitCode =
                    process.ExitCode,

                StdOut =
                    stdout,

                StdErr =
                    stderr
            };
        }

        private static string
            CombineProcessOutput(
                string? stdout,
                string? stderr)
        {
            return string.Join(
                Environment.NewLine,
                new[]
                {
                    stdout?.Trim(),
                    stderr?.Trim()
                }
                .Where(
                    x => !string.IsNullOrWhiteSpace(x)));
        }

        private static string
            GenerateStableStudyInstanceUid(
                string accessionNumber)
        {
            var input =
                Encoding.UTF8.GetBytes(
                    "LIS-PACS-STUDY|" +
                    accessionNumber.Trim());

            var hash =
                SHA256.HashData(input);

            // DICOM's registered UUID-derived UID root is 2.25.
            // Use 128 deterministic bits from SHA-256.
            var bytes =
                hash.Take(16).ToArray();

            var number =
                new BigInteger(
                    bytes,
                    isUnsigned: true,
                    isBigEndian: true);

            return
                $"2.25.{number}";
        }

        private static string
            NormalizeSex(
                string? value)
        {
            if (string.IsNullOrWhiteSpace(
                    value))
            {
                return "";
            }

            value =
                value.Trim()
                    .ToUpperInvariant();

            if (value == "NAM" ||
                value == "MALE" ||
                value == "M" ||
                value == "1")
            {
                return "M";
            }

            if (value == "NỮ" ||
                value == "NU" ||
                value == "FEMALE" ||
                value == "F" ||
                value == "0" ||
                value == "2")
            {
                return "F";
            }

            return "";
        }

        private static string
            ToDicomPersonName(
                string? value)
        {
            if (string.IsNullOrWhiteSpace(
                    value))
            {
                return "";
            }

            return SafeDicomValue(
                    value)
                .Replace(" ", "^");
        }

        private static string
            SafeDicomValue(
                string? value)
        {
            if (string.IsNullOrWhiteSpace(
                    value))
            {
                return "";
            }

            return RemoveInvalidDicomChars(
                RemoveVietnameseDiacritics(
                    value.Trim()));
        }

        private static string
            RemoveVietnameseDiacritics(
                string value)
        {
            value =
                value
                    .Replace('đ', 'd')
                    .Replace('Đ', 'D');

            var normalized =
                value.Normalize(
                    NormalizationForm.FormD);

            var sb =
                new StringBuilder();

            foreach (var character in normalized)
            {
                if (CharUnicodeInfo
                    .GetUnicodeCategory(character)
                    != UnicodeCategory.NonSpacingMark)
                {
                    sb.Append(character);
                }
            }

            return sb
                .ToString()
                .Normalize(
                    NormalizationForm.FormC);
        }

        private static string
            RemoveInvalidDicomChars(
                string value)
        {
            return value
                .Replace("[", "(")
                .Replace("]", ")")
                .Replace("\r", " ")
                .Replace("\n", " ")
                .Trim();
        }

        private static string
            MakeSafeFileName(
                string value)
        {
            foreach (var character in
                Path.GetInvalidFileNameChars())
            {
                value =
                    value.Replace(
                        character,
                        '_');
            }

            return value.Trim();
        }

