        public async Task<PacsMwlValidationResult>
            GenerateMwlValidationFixtureAsync(
                long resultCDHAId,
                string categoryCode,
                DateTime? scheduledAt = null)
        {
            var response = new PacsMwlValidationResult
            {
                Success = false,
                ResultCDHAId = resultCDHAId,
                CategoryCode = NormalizeCategoryCode(categoryCode)
            };

            if (resultCDHAId <= 0)
            {
                response.ErrorCode = "INVALID_RESULT_ID";
                response.Message = "ResultCDHAId không hợp lệ.";
                return response;
            }

            if (string.IsNullOrWhiteSpace(response.CategoryCode))
            {
                response.ErrorCode = "INVALID_CATEGORY";
                response.Message = "CategoryCode không được rỗng.";
                return response;
            }

            try
            {
                // 1. Accession must already follow the 03-04 contract.
                // This method is allowed to ensure it if still missing.
                var accessionResult =
                    await EnsureAccessionNumberAsync(
                        resultCDHAId,
                        response.CategoryCode);

                if (!accessionResult.Success)
                {
                    response.ErrorCode =
                        accessionResult.ErrorCode;

                    response.Message =
                        accessionResult.Message;

                    response.ErrorMessage =
                        accessionResult.ErrorMessage;

                    return response;
                }

                response.AccessionNumber =
                    accessionResult.AccessionNumber;

                // 2. Read the clinical source data.
                var resultCDHA =
                    await _context.ResultCDHAs
                        .AsNoTracking()
                        .Include(x => x.Patient)
                        .Include(x => x.Service)
                            .ThenInclude(x => x.Category)
                        .Include(x => x.Doctor)
                        .FirstOrDefaultAsync(
                            x => x.Id == resultCDHAId);

                if (resultCDHA == null)
                {
                    response.ErrorCode =
                        "RESULT_NOT_FOUND";

                    response.Message =
                        $"Không tìm thấy ResultCDHAId={resultCDHAId}.";

                    return response;
                }

                if (resultCDHA.Patient == null)
                {
                    response.ErrorCode =
                        "PATIENT_NOT_FOUND";

                    response.Message =
                        $"ResultCDHAId={resultCDHAId} không có Patient.";

                    return response;
                }

                if (resultCDHA.Service == null)
                {
                    response.ErrorCode =
                        "SERVICE_NOT_FOUND";

                    response.Message =
                        $"ResultCDHAId={resultCDHAId} không có Service.";

                    return response;
                }

                var actualCategoryCode =
                    NormalizeCategoryCode(
                        resultCDHA.Service.Category?.Code);

                if (!string.IsNullOrWhiteSpace(
                        actualCategoryCode) &&
                    actualCategoryCode !=
                        response.CategoryCode)
                {
                    response.ErrorCode =
                        "CATEGORY_MISMATCH";

                    response.Message =
                        $"CategoryCode request={response.CategoryCode} " +
                        $"không khớp Service.Category.Code={actualCategoryCode}.";

                    return response;
                }

                // 3. Build a pure draft.
                // No PacsWorklistItems row is created in 03-05.
                var modality =
                    ResolveDicomModality(
                        response.CategoryCode);

                var stationAe =
                    ResolveScheduledStationAETitle(
                        response.CategoryCode,
                        modality);

                var stationName =
                    ResolveScheduledStationName(
                        response.CategoryCode,
                        modality);

                var location =
                    ResolveScheduledProcedureStepLocation(
                        response.CategoryCode,
                        modality);

                var procedureStatus =
                    ResolveScheduledProcedureStepStatus();

                var scheduledDateTime =
                    scheduledAt
                    ?? ResolveScheduledDateTime(
                        resultCDHA,
                        response.CategoryCode)
                    ?? DateTime.Now;

                var patient =
                    resultCDHA.Patient;

                var service =
                    resultCDHA.Service;

                var draft =
                    new PacsMwlDraft
                    {
                        ResultCDHAId =
                            resultCDHA.Id,

                        AccessionNumber =
                            accessionResult.AccessionNumber,

                        StudyInstanceUID =
                            GenerateStableStudyInstanceUid(
                                accessionResult.AccessionNumber),

                        PatientCode =
                            patient.PatientId?.Trim()
                            ?? "",

                        PatientName =
                            patient.PatientName?.Trim()
                            ?? "",

                        // Project A currently has Patient.Age (DateTime?)
                        // but no explicit BirthDate property. A previous
                        // PACS baseline already documented that Age must
                        // not be interpreted as DOB. Therefore 03-05
                        // deliberately leaves PatientBirthDate empty.
                        PatientBirthDate = null,

                        PatientSex =
                            NormalizeSex(
                                patient.Sex),

                        ReferringPhysicianName =
                            resultCDHA.Doctor?.Name
                            ?? "",

                        InstitutionName =
                            _configuration[
                                "Pacs:InstitutionName"]
                            ?? "",

                        ServiceCode =
                            service.Code
                            ?? "",

                        ServiceName =
                            service.Name
                            ?? "",

                        CategoryCode =
                            response.CategoryCode,

                        Modality =
                            modality,

                        RequestedProcedureId =
                            accessionResult.AccessionNumber,

                        RequestedProcedureDescription =
                            service.Name
                            ?? "",

                        ScheduledStationAETitle =
                            stationAe,

                        ScheduledStationName =
                            stationName,

                        ScheduledProcedureStepLocation =
                            location,

                        ScheduledProcedureStepStatus =
                            procedureStatus,

                        ScheduledProcedureStepId =
                            accessionResult.AccessionNumber,

                        ScheduledProcedureStepStartDate =
                            scheduledDateTime.Date,

                        ScheduledProcedureStepStartTime =
                            scheduledDateTime.TimeOfDay,

                        ScheduledProcedureStepDescription =
                            service.Name
                            ?? "",

                        ScheduledPerformingPhysicianName =
                            "",

                        StudyDescription =
                            service.Name
                            ?? ""
                    };

                response.Modality =
                    draft.Modality;

                response.ScheduledStationAETitle =
                    draft.ScheduledStationAETitle;

                response.StudyInstanceUID =
                    draft.StudyInstanceUID;

                // 4. Work strictly in staging.
                var stagingFolder =
                    GetWorklistStagingFolder();

                Directory.CreateDirectory(
                    stagingFolder);

                var safeAccession =
                    MakeSafeFileName(
                        draft.AccessionNumber);

                var dumpFileName =
                    $"VALIDATE_{safeAccession}.dump";

                var wlFileName =
                    $"VALIDATE_{safeAccession}.wl";

                var dumpFilePath =
                    Path.Combine(
                        stagingFolder,
                        dumpFileName);

                var wlFilePath =
                    Path.Combine(
                        stagingFolder,
                        wlFileName);

                response.DumpFilePath =
                    dumpFilePath;

                response.WorklistFilePath =
                    wlFilePath;

                // idempotent validation run
                TryDeleteFile(dumpFilePath);
                TryDeleteFile(wlFilePath);

                var dumpContent =
                    BuildWorklistDump(draft);

                await File.WriteAllTextAsync(
                    dumpFilePath,
                    dumpContent,
                    new UTF8Encoding(false));

                // 5. dump2dcm
                var convert =
                    await RunProcessAsync(
                        GetDump2DcmPath(),
                        new[]
                        {
                            dumpFilePath,
                            wlFilePath
                        },
                        stagingFolder,
                        timeoutMilliseconds: 15000);

                response.Dump2DcmExitCode =
                    convert.ExitCode;

                response.Dump2DcmOutput =
                    CombineProcessOutput(
                        convert.StdOut,
                        convert.StdErr);

                if (!convert.Success ||
                    !File.Exists(wlFilePath))
                {
                    response.ErrorCode =
                        "DUMP2DCM_FAILED";

                    response.Message =
                        "dump2dcm không tạo được Worklist DICOM hợp lệ.";

                    return response;
                }

                // 6. dcmdump
                var dumpCheck =
                    await RunProcessAsync(
                        GetDcmDumpPath(),
                        new[]
                        {
                            "+L",
                            wlFilePath
                        },
                        stagingFolder,
                        timeoutMilliseconds: 15000);

                response.DcmDumpExitCode =
                    dumpCheck.ExitCode;

                response.DcmDumpOutput =
                    CombineProcessOutput(
                        dumpCheck.StdOut,
                        dumpCheck.StdErr);

                if (!dumpCheck.Success)
                {
                    response.ErrorCode =
                        "DCMDUMP_FAILED";

                    response.Message =
                        "dcmdump không đọc được file Worklist.";

                    return response;
                }

                // 7. Validate the exact values that matter for
                // MWL identity and modality filtering.
                var validations =
                    BuildMwlValidationChecks(
                        response.DcmDumpOutput,
                        draft);

                response.Validations =
                    validations;

                response.ValidationPassed =
                    validations.All(x => x.Passed);

                if (!response.ValidationPassed)
                {
                    response.ErrorCode =
                        "MWL_TAG_VALIDATION_FAILED";

                    response.Message =
                        "File .wl đã được tạo nhưng thiếu hoặc sai tag bắt buộc.";

                    return response;
                }

                // Deliberately no copy to WorklistFolder here.
                // 03-06 owns DB row + publish semantics.
                response.Success = true;
                response.Message =
                    "Tạo và validate DICOM MWL trong staging thành công. Chưa publish sang Orthanc.";

                return response;
            }
            catch (Exception ex)
            {
                response.ErrorCode =
                    "MWL_VALIDATION_ERROR";

                response.Message =
                    "Không thể tạo MWL validation fixture.";

                response.ErrorMessage =
                    ex.ToString();

                return response;
            }
        }


