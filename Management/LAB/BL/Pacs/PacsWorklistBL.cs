        private static bool IsCanonicalAccession(
            string accessionNumber,
            string prefix)
        {
            if (string.IsNullOrWhiteSpace(accessionNumber))
                return false;

            accessionNumber =
                accessionNumber.Trim().ToUpperInvariant();

            prefix =
                prefix.Trim().ToUpperInvariant();

            if (!accessionNumber.StartsWith(
                    prefix,
                    StringComparison.Ordinal))
            {
                return false;
            }

            if (accessionNumber.Length !=
                prefix.Length + AccessionSuffixLength)
            {
                return false;
            }

            var suffix =
                accessionNumber.Substring(prefix.Length);

            if (suffix.Length != AccessionSuffixLength ||
                !suffix.All(char.IsDigit))
            {
                return false;
            }

            return !IsOldDateBasedAccessionSuffix(suffix);
        }

        private static bool IsOldDateBasedAccessionSuffix(string suffix)
        {
            if (string.IsNullOrWhiteSpace(suffix) ||
                suffix.Length != AccessionSuffixLength)
            {
                return false;
            }

            var datePart = suffix.Substring(0, 6);

            return DateTime.TryParseExact(
                datePart,
                "yyMMdd",
                CultureInfo.InvariantCulture,
                DateTimeStyles.None,
                out _);
        }


