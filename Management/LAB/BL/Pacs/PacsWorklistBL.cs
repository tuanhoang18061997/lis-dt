        public async Task<PacsPatientWorklistCreateResult>
            CreateWorklistForPatientAsync(
                long patientId,
                string categoryCode,
                DateTime? scheduledAt = null,
                long? userId = null)
        {
            var response =
                new PacsPatientWorklistCreateResult
                {
                    Success = false,
                    PatientId = patientId,
                    CategoryCode =
                        NormalizeCategoryCode(categoryCode)
                };

            if (patientId <= 0)
            {
                response.ErrorCode = "INVALID_PATIENT_ID";
                response.Message = "PatientId không hợp lệ.";
                return response;
            }

            if (string.IsNullOrWhiteSpace(
                    response.CategoryCode))
            {
                response.ErrorCode = "INVALID_CATEGORY";
                response.Message =
                    "CategoryCode không được rỗng.";
                return response;
            }

            try
            {
                // Query IDs only and do not track the ResultCDHA entities.
                // Each item is reloaded inside the already-tested 03-06
                // result-level pipeline after its per-result file lock.
                var resultIds =
                    await _context.ResultCDHAs
                        .AsNoTracking()
                        .Where(x =>
                            x.PatientId == patientId &&
                            x.Service != null &&
                            x.Service.Category != null &&
                            x.Service.Category.Code != null &&
                            x.Service.Category.Code.ToUpper() ==
                                response.CategoryCode)
                        .OrderBy(x => x.Id)
                        .Select(x => x.Id)
                        .ToListAsync();

                response.TotalResultCDHA =
                    resultIds.Count;

                if (resultIds.Count == 0)
                {
                    response.Success = true;
                    response.Message =
                        $"Không có ResultCDHA nào của PatientId={patientId} " +
                        $"thuộc CategoryCode={response.CategoryCode} để tạo Worklist.";
                    return response;
                }

                foreach (var resultCDHAId in resultIds)
                {
                    PacsWorklistCreateResult itemResult;

                    try
                    {
                        itemResult =
                            await CreateWorklistForResultCDHAAsync(
                                resultCDHAId,
                                response.CategoryCode,
                                scheduledAt,
                                userId);
                    }
                    catch (Exception ex)
                    {
                        // Keep the batch observable and continue with the
                        // remaining ResultCDHA records. The result-level method
                        // normally converts exceptions into a failure result,
                        // so this is only a last-resort isolation guard.
                        itemResult =
                            new PacsWorklistCreateResult
                            {
                                Success = false,
                                Skipped = false,
                                ResultCDHAId = resultCDHAId,
                                ErrorCode =
                                    "PATIENT_BATCH_ITEM_ERROR",
                                Message =
                                    "Có lỗi ngoài dự kiến khi tạo Worklist cho ResultCDHA trong patient batch.",
                                ErrorMessage =
                                    ex.ToString()
                            };
                    }

                    response.Items.Add(itemResult);

                    if (!itemResult.Success)
                    {
                        response.TotalFailed++;
                    }
                    else if (itemResult.Skipped)
                    {
                        response.TotalSkipped++;
                    }
                    else
                    {
                        response.TotalCreated++;
                    }
                }

                response.Success =
                    response.TotalFailed == 0;

                response.ErrorCode =
                    response.Success
                        ? string.Empty
                        : "PATIENT_BATCH_PARTIAL_FAILURE";

                response.Message =
                    response.Success
                        ? $"Tạo Worklist cho PatientId={patientId}, " +
                          $"CategoryCode={response.CategoryCode} hoàn tất. " +
                          $"Created={response.TotalCreated}, " +
                          $"Skipped={response.TotalSkipped}, " +
                          $"Failed={response.TotalFailed}."
                        : $"Tạo Worklist cho PatientId={patientId}, " +
                          $"CategoryCode={response.CategoryCode} có lỗi một phần. " +
                          $"Created={response.TotalCreated}, " +
                          $"Skipped={response.TotalSkipped}, " +
                          $"Failed={response.TotalFailed}.";

                return response;
            }
            catch (Exception ex)
            {
                response.Success = false;
                response.ErrorCode =
                    "PATIENT_WORKLIST_ORCHESTRATION_ERROR";
                response.Message =
                    "Không thể orchestration PACS Worklist theo Patient.";
                response.ErrorMessage =
                    ex.ToString();
                return response;
            }
        }

