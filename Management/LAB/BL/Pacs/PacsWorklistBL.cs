        public async Task<PacsAccessionEnsureResult>
            EnsureAccessionNumberAsync(
                long resultCDHAId,
                string categoryCode)
        {
            var response = new PacsAccessionEnsureResult
            {
                Success = false,
                ResultCDHAId = resultCDHAId,
                CategoryCode = NormalizeCategoryCode(categoryCode)
            };

            if (resultCDHAId <= 0)
            {
                response.ErrorCode = "INVALID_RESULT_ID";
                response.Message = "ResultCDHAId không hợp lệ.";
                return response;
            }

            string prefix;

            try
            {
                prefix = ResolveAccessionPrefix(response.CategoryCode);
                response.Prefix = prefix;
            }
            catch (Exception ex)
            {
                response.ErrorCode = "UNSUPPORTED_CATEGORY";
                response.Message = ex.Message;
                return response;
            }

            try
            {
                var resultCDHA = await _context.ResultCDHAs
                    .FirstOrDefaultAsync(x => x.Id == resultCDHAId);

                if (resultCDHA == null)
                {
                    response.ErrorCode = "RESULT_NOT_FOUND";
                    response.Message =
                        $"Không tìm thấy ResultCDHAId={resultCDHAId}.";
                    return response;
                }

                if (!string.IsNullOrWhiteSpace(resultCDHA.AccessionNumber))
                {
                    var existing = resultCDHA.AccessionNumber.Trim();

                    var conflict =
                        await FindAccessionConflictAsync(
                            resultCDHAId,
                            existing);

                    if (!string.IsNullOrWhiteSpace(conflict))
                    {
                        response.ErrorCode = "ACCESSION_CONFLICT";
                        response.AccessionNumber = existing;
                        response.Message = conflict;
                        return response;
                    }

                    if (resultCDHA.AccessionNumber != existing)
                    {
                        resultCDHA.AccessionNumber = existing;
                        await _context.SaveChangesAsync();
                    }

                    response.Success = true;
                    response.Existing = true;
                    response.Generated = false;
                    response.AccessionNumber = existing;
                    response.CanonicalFormat =
                        IsCanonicalAccession(existing, prefix);
                    response.Message =
                        response.CanonicalFormat
                            ? "ResultCDHA đã có AccessionNumber canonical, giữ nguyên."
                            : "ResultCDHA đã có AccessionNumber legacy/non-canonical, giữ nguyên để không phá liên kết DICOM hiện hữu.";

                    return response;
                }

                await using var transaction =
                    await _context.Database.BeginTransactionAsync(
                        IsolationLevel.Serializable);

                try
                {
                    await AcquireAccessionLockAsync(prefix);

                    // HOTFIX-01:
                    // The entity was already tracked by the initial query.
                    // A normal LINQ query after waiting for sp_getapplock can
                    // return that stale tracked instance. Force a database
                    // reload after the lock so this request sees an accession
                    // generated by the request that acquired the lock first.
                    await _context.Entry(resultCDHA).ReloadAsync();

                    if (!string.IsNullOrWhiteSpace(
                        resultCDHA.AccessionNumber))
                    {
                        var existingAfterLock =
                            resultCDHA.AccessionNumber.Trim();

                        var conflictAfterLock =
                            await FindAccessionConflictAsync(
                                resultCDHAId,
                                existingAfterLock);

                        if (!string.IsNullOrWhiteSpace(conflictAfterLock))
                        {
                            await transaction.RollbackAsync();

                            response.ErrorCode = "ACCESSION_CONFLICT";
                            response.AccessionNumber = existingAfterLock;
                            response.Message = conflictAfterLock;
                            return response;
                        }

                        await transaction.CommitAsync();

                        response.Success = true;
                        response.Existing = true;
                        response.Generated = false;
                        response.AccessionNumber = existingAfterLock;
                        response.CanonicalFormat =
                            IsCanonicalAccession(
                                existingAfterLock,
                                prefix);
                        response.Message =
                            "AccessionNumber đã được request khác tạo trước, dùng lại giá trị hiện có.";

                        return response;
                    }

                    var nextAccession =
                        await GenerateNextAccessionNumberAsync(prefix);

                    var generatedConflict =
                        await FindAccessionConflictAsync(
                            resultCDHAId,
                            nextAccession);

                    if (!string.IsNullOrWhiteSpace(generatedConflict))
                    {
                        await transaction.RollbackAsync();

                        response.ErrorCode = "ACCESSION_CONFLICT";
                        response.AccessionNumber = nextAccession;
                        response.Message = generatedConflict;
                        return response;
                    }

                    resultCDHA.AccessionNumber = nextAccession;

                    await _context.SaveChangesAsync();
                    await transaction.CommitAsync();

                    response.Success = true;
                    response.Existing = false;
                    response.Generated = true;
                    response.CanonicalFormat = true;
                    response.AccessionNumber = nextAccession;
                    response.Message =
                        $"Đã tạo AccessionNumber canonical: {nextAccession}";

                    return response;
                }
                catch
                {
                    await transaction.RollbackAsync();
                    throw;
                }
            }
            catch (Exception ex)
            {
                response.ErrorCode = "ACCESSION_GENERATION_ERROR";
                response.Message = "Không thể đảm bảo AccessionNumber.";
                response.ErrorMessage = ex.ToString();
                return response;
            }
        }


