        private static void
            AddValidation(
                List<PacsMwlTagValidation> checks,
                string output,
                string name,
                string expectedValue)
        {
            expectedValue ??= "";

            var passed =
                !string.IsNullOrWhiteSpace(
                    expectedValue)
                &&
